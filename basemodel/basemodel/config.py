# `fit_on: "eval"` — 이 프리셋만 **train 이 아니라 평가 구간(valid)에서** 맞춘다.
#   나머지는 train 에서 맞춰도 valid 로 잘 전이된다(기본형 train적합 33.3% vs valid교차적합
#   33.7%). 역배형만 안 된다. 이유는 신경망이 train 에 과적합돼 있어 **in-sample 에서는
#   펀더멘털 점수가 실제보다 날카롭기** 때문이다. 시장 계수 m 은 그 날카로움과 시장 신호의
#   교환비를 정하는 값이라 in-sample 에서 고르면 과하게 음수가 된다.
#   실측: train 곡선은 m=-0.50 에서 정점인데 valid 곡선은 m=-0.30 에서 정점이고,
#   valid 에서 -0.50 을 쓰면 고배당 적중이 0.56% → 0.16% 로 떨어진다.
#   top-1 목적함수는 경주마다 값이 나오는 조밀한 신호라 이 문제가 안 생기지만,
#   고배당 적중은 1% 미만 희귀사건이라 그대로 드러난다.
#   → 역배형 m 은 valid 에서 맞추고, 낙관 편향은 2-fold 교차적합으로 따로 보고한다.

